-- TDash: diagnostico do Faturamento (parte 2) - IBS e CBS pela F2D, devolucoes e retencoes
--
-- SOMENTE LEITURA: so SELECT, nada e criado nem alterado. Sem dado de pessoa.
-- Continua o diagnostico-faturamento-resultado.sql. O que a primeira rodada mostrou:
--   * cada item de nota gera 3 linhas na F2D (TR0001, TR0002, TR0003) e a CJ3 repete linhas por item (3, 6, 7, 9, 12);
--     por isso o IBS/CBS deve ser somado pela F2D (F2D_VALOR), e nao pela CJ3, para nao contar em dobro;
--   * ICMS, PIS e COFINS estao em D2_VALICM, D2_VALIMP5 e D2_VALIMP6 (IMP1 a IMP4 sao zero); IPI, ICMS-ST e ISS sao pequenos;
--   * D2_VALPIS, D2_VALCOF, D2_VALCSL e D2_VALIRRF aparecem so em 12 itens (retencoes de servico).
-- Esta parte confere: o que sao TR0001 a TR0003, em que meses ha IBS/CBS, o que a F2D tem para devolucoes (SD1) e
-- como se comportam as retencoes.
--
-- Antes de rodar:
--   * Troque o sufixo 010 (empresa 01) pelo da empresa que o TDash vai usar.
--   * @FILIAL: NULL = todas as filiais, ou o codigo como gravado (qualquer tamanho).
--   * Periodo: ultimos 12 meses. Escrito para SQL Server. Mande o resultado de cada consulta numerada.

DECLARE @FILIAL VARCHAR(20) = NULL;
DECLARE @DESDE  CHAR(8) = CONVERT(CHAR(8), DATEADD(MONTH, -12, GETDATE()), 112);

-- 1) Tributos da F2D nas saidas do periodo: aliquota minima e maxima, base e valor (o que e cada TR000x?)
SELECT F2.F2D_TRIB AS TRIBUTO, F2.F2D_TABELA AS TABELA_ORIGEM, COUNT(*) AS LINHAS,
       SUM(F2.F2D_BASE) AS BASE, SUM(F2.F2D_VALOR) AS VALOR,
       MIN(F2.F2D_ALIQ) AS ALIQ_MIN, MAX(F2.F2D_ALIQ) AS ALIQ_MAX,
       SUM(CASE WHEN F2.F2D_DTEXCL <> ' ' THEN 1 ELSE 0 END) AS LINHAS_EXCLUIDAS
FROM F2D010 F2
INNER JOIN SD2010 D2 ON D2.D2_IDTRIB = F2.F2D_IDREL AND D2.D_E_L_E_T_ = ' ' AND D2.D2_TIPO = 'N' AND D2.D2_EMISSAO >= @DESDE
                    AND (@FILIAL IS NULL OR D2.D2_FILIAL = @FILIAL)
                    AND EXISTS (SELECT 1 FROM SF4010 F4 WHERE F4.F4_CODIGO = D2.D2_TES AND F4.F4_DUPLIC = 'S' AND F4.D_E_L_E_T_ = ' ')
WHERE F2.D_E_L_E_T_ = ' '
GROUP BY F2.F2D_TRIB, F2.F2D_TABELA
ORDER BY F2.F2D_TRIB;

-- 2) Por mes e tributo (saidas): a partir de que mes ha IBS/CBS e quanto
SELECT SUBSTRING(D2.D2_EMISSAO, 1, 6) AS MES, F2.F2D_TRIB AS TRIBUTO, COUNT(*) AS LINHAS,
       SUM(F2.F2D_BASE) AS BASE, SUM(F2.F2D_VALOR) AS VALOR
FROM F2D010 F2
INNER JOIN SD2010 D2 ON D2.D2_IDTRIB = F2.F2D_IDREL AND D2.D_E_L_E_T_ = ' ' AND D2.D2_TIPO = 'N' AND D2.D2_EMISSAO >= @DESDE
                    AND (@FILIAL IS NULL OR D2.D2_FILIAL = @FILIAL)
                    AND EXISTS (SELECT 1 FROM SF4010 F4 WHERE F4.F4_CODIGO = D2.D2_TES AND F4.F4_DUPLIC = 'S' AND F4.D_E_L_E_T_ = ' ')
WHERE F2.D_E_L_E_T_ = ' ' AND F2.F2D_DTEXCL = ' '
GROUP BY SUBSTRING(D2.D2_EMISSAO, 1, 6), F2.F2D_TRIB
ORDER BY MES, TRIBUTO;

-- 3) Itens de saida por mes: com e sem ID de tributo (mostra os meses sem calculo pelo Configurador de Tributos)
SELECT SUBSTRING(D2.D2_EMISSAO, 1, 6) AS MES, COUNT(*) AS ITENS,
       SUM(CASE WHEN D2.D2_IDTRIB <> ' ' THEN 1 ELSE 0 END) AS COM_IDTRIB,
       SUM(CASE WHEN D2.D2_IDTRIB = ' ' THEN 1 ELSE 0 END) AS SEM_IDTRIB,
       SUM(CASE WHEN D2.D2_IDTRIB = ' ' THEN D2.D2_TOTAL ELSE 0 END) AS TOTAL_SEM_IDTRIB
FROM SD2010 D2
WHERE D2.D_E_L_E_T_ = ' ' AND D2.D2_TIPO = 'N' AND D2.D2_EMISSAO >= @DESDE AND (@FILIAL IS NULL OR D2.D2_FILIAL = @FILIAL)
  AND EXISTS (SELECT 1 FROM SF4010 F4 WHERE F4.F4_CODIGO = D2.D2_TES AND F4.F4_DUPLIC = 'S' AND F4.D_E_L_E_T_ = ' ')
GROUP BY SUBSTRING(D2.D2_EMISSAO, 1, 6)
ORDER BY MES;

-- 4) Tabelas de origem que a F2D guarda (SD2, SD1, outras)
SELECT F2D_TABELA AS TABELA_ORIGEM, COUNT(*) AS LINHAS FROM F2D010 WHERE D_E_L_E_T_ = ' ' GROUP BY F2D_TABELA ORDER BY F2D_TABELA;

-- 5) Devolucoes (SD1 tipo D): itens com ID de tributo e o IBS/CBS por tributo
SELECT COUNT(*) AS ITENS_DEVOLUCAO, SUM(CASE WHEN D1.D1_IDTRIB <> ' ' THEN 1 ELSE 0 END) AS COM_IDTRIB
FROM SD1010 D1
WHERE D1.D_E_L_E_T_ = ' ' AND D1.D1_TIPO = 'D' AND D1.D1_DTDIGIT >= @DESDE AND (@FILIAL IS NULL OR D1.D1_FILIAL = @FILIAL);

SELECT F2.F2D_TRIB AS TRIBUTO, COUNT(*) AS LINHAS, SUM(F2.F2D_VALOR) AS VALOR
FROM F2D010 F2
INNER JOIN SD1010 D1 ON D1.D1_IDTRIB = F2.F2D_IDREL AND D1.D_E_L_E_T_ = ' ' AND D1.D1_TIPO = 'D' AND D1.D1_DTDIGIT >= @DESDE
                    AND (@FILIAL IS NULL OR D1.D1_FILIAL = @FILIAL)
WHERE F2.D_E_L_E_T_ = ' ' AND F2.F2D_DTEXCL = ' '
GROUP BY F2.F2D_TRIB
ORDER BY F2.F2D_TRIB;

-- 6) F2D_VALOR bate com a CJ3? (por linha da F2D: igual ao maior CJ3_VLTRIB, ou igual a soma das linhas da CJ3)
SELECT SUM(CASE WHEN ABS(F2D_VALOR - VLTRIB_MAIOR) < 0.005 THEN 1 ELSE 0 END) AS IGUAL_AO_MAIOR_CJ3,
       SUM(CASE WHEN ABS(F2D_VALOR - VLTRIB_SOMA) < 0.005 THEN 1 ELSE 0 END) AS IGUAL_A_SOMA_CJ3,
       SUM(CASE WHEN ABS(F2D_VALOR - VLTRIB_MAIOR) >= 0.005 AND ABS(F2D_VALOR - VLTRIB_SOMA) >= 0.005 THEN 1 ELSE 0 END) AS DIFERENTE_DOS_DOIS,
       COUNT(*) AS LINHAS_F2D
FROM (
  SELECT F2.F2D_ID, F2.F2D_VALOR, ISNULL(MAX(J3.CJ3_VLTRIB), 0) AS VLTRIB_MAIOR, ISNULL(SUM(J3.CJ3_VLTRIB), 0) AS VLTRIB_SOMA
  FROM F2D010 F2
  INNER JOIN SD2010 D2 ON D2.D2_IDTRIB = F2.F2D_IDREL AND D2.D_E_L_E_T_ = ' ' AND D2.D2_TIPO = 'N' AND D2.D2_EMISSAO >= @DESDE
                      AND (@FILIAL IS NULL OR D2.D2_FILIAL = @FILIAL)
  LEFT JOIN CJ3010 J3 ON J3.CJ3_IDF2D = F2.F2D_ID AND J3.D_E_L_E_T_ = ' ' AND J3.CJ3_DTEXCL = ' '
  WHERE F2.D_E_L_E_T_ = ' ' AND F2.F2D_DTEXCL = ' '
  GROUP BY F2.F2D_ID, F2.F2D_VALOR
) X;

-- 7) Por que a CJ3 tem varias linhas para a mesma linha da F2D? (amostra de 15 linhas)
SELECT TOP 15 F2.F2D_TRIB AS TRIBUTO_F2D, F2.F2D_VALOR AS VALOR_F2D, J3.CJ3_TRIB AS TRIBUTO_CJ3, J3.CJ3_VLTRIB AS VALOR_CJ3,
       J3.CJ3_CST AS CST, J3.CJ3_NLIVRO AS LIVRO, J3.CJ3_CCT AS CCT, J3.CJ3_INDOP AS INDOP, J3.CJ3_DTEXCL AS EXCLUSAO
FROM F2D010 F2
INNER JOIN CJ3010 J3 ON J3.CJ3_IDF2D = F2.F2D_ID AND J3.D_E_L_E_T_ = ' '
WHERE F2.D_E_L_E_T_ = ' '
  AND F2.F2D_ID IN (SELECT CJ3_IDF2D FROM CJ3010 WHERE D_E_L_E_T_ = ' ' GROUP BY CJ3_IDF2D HAVING COUNT(*) > 1)
ORDER BY F2.F2D_ID, J3.R_E_C_N_O_;

-- 8) Cadastro de impostos variaveis (SFB): confirma qual D2_VALIMPn e PIS, COFINS etc.
SELECT * FROM SFB010 WHERE D_E_L_E_T_ = ' ' ORDER BY FB_CODIGO;

-- 9) Itens com retencao ou ISS (os 12 itens de servico): como se somam com PIS/COFINS de apuracao, para nao contar em dobro
SELECT D2.D2_TES AS TES, COUNT(*) AS ITENS, SUM(D2.D2_TOTAL) AS TOTAL,
       SUM(D2.D2_VALISS) AS ISS, SUM(D2.D2_VALIMP5) AS IMP5, SUM(D2.D2_VALIMP6) AS IMP6,
       SUM(D2.D2_VALCOF) AS COFINS_RETIDO, SUM(D2.D2_VALPIS) AS PIS_RETIDO, SUM(D2.D2_VALCSL) AS CSLL_RETIDO,
       SUM(D2.D2_VALIRRF) AS IRRF_RETIDO, SUM(D2.D2_VALICM) AS ICMS
FROM SD2010 D2
WHERE D2.D_E_L_E_T_ = ' ' AND D2.D2_TIPO = 'N' AND D2.D2_EMISSAO >= @DESDE AND (@FILIAL IS NULL OR D2.D2_FILIAL = @FILIAL)
  AND (D2.D2_VALIRRF > 0 OR D2.D2_VALISS > 0 OR D2.D2_VALCOF > 0 OR D2.D2_VALPIS > 0 OR D2.D2_VALCSL > 0)
GROUP BY D2.D2_TES
ORDER BY D2.D2_TES;

-- 10) Custo por mes: quanto do valor vendido tem custo gravado, e o custo em % da venda (mes aberto costuma ficar provisorio)
SELECT SUBSTRING(D2.D2_EMISSAO, 1, 6) AS MES, SUM(D2.D2_TOTAL) AS VENDA, SUM(D2.D2_CUSTO1) AS CUSTO,
       CASE WHEN SUM(D2.D2_TOTAL) = 0 THEN 0 ELSE SUM(D2.D2_CUSTO1) / SUM(D2.D2_TOTAL) * 100 END AS CUSTO_PCT_DA_VENDA,
       SUM(CASE WHEN D2.D2_CUSTO1 = 0 THEN D2.D2_TOTAL ELSE 0 END) AS VENDA_SEM_CUSTO
FROM SD2010 D2
WHERE D2.D_E_L_E_T_ = ' ' AND D2.D2_TIPO = 'N' AND D2.D2_EMISSAO >= @DESDE AND (@FILIAL IS NULL OR D2.D2_FILIAL = @FILIAL)
  AND EXISTS (SELECT 1 FROM SF4010 F4 WHERE F4.F4_CODIGO = D2.D2_TES AND F4.F4_DUPLIC = 'S' AND F4.D_E_L_E_T_ = ' ')
GROUP BY SUBSTRING(D2.D2_EMISSAO, 1, 6)
ORDER BY MES;
