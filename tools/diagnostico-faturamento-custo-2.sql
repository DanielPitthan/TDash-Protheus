-- TDash: diagnostico do Faturamento (parte 2 do custo) - por que estes produtos sairam com custo zero em 07/2026
--
-- SOMENTE LEITURA: so SELECT, nada e criado nem alterado. Sem dado de pessoa.
-- Produtos de TES que movimenta estoque (501/502) que sairam com D2_CUSTO1 = 0 num mes ja fechado (MV_ULMES 20260930).
-- Antes de rodar: troque o sufixo 010 pelo da empresa e confira a filial. Escrito para SQL Server.

DECLARE @FILIAL VARCHAR(10) = '1001';
DECLARE @DE     VARCHAR(8)  = '20260701';
DECLARE @ATE    VARCHAR(8)  = '20260731';

-- 1) Saldo e custo medio atual do produto no armazem 01 (SB2)
SELECT RTRIM(B2_COD) AS PRODUTO, B2_LOCAL AS ARMAZEM, B2_QATU AS SALDO, B2_CM1 AS CUSTO_MEDIO, B2_VATU1 AS VALOR_ESTOQUE
FROM SB2010
WHERE B2_FILIAL = @FILIAL AND B2_COD IN ('THC31002IBCBR', 'THC31003CIBR', 'BR0727') AND D_E_L_E_T_ = ' '
ORDER BY B2_COD, B2_LOCAL;

-- 2) Saldo de fechamento (SB9) de junho a setembro: quantidade, valor e custo medio do inicio de cada mes
SELECT RTRIM(B9_COD) AS PRODUTO, B9_LOCAL AS ARMAZEM, B9_DATA AS FECHAMENTO, B9_QINI AS QUANT, B9_VINI1 AS VALOR, B9_CM1 AS CUSTO_MEDIO
FROM SB9010
WHERE B9_FILIAL = @FILIAL AND B9_COD IN ('THC31002IBCBR', 'THC31003CIBR', 'BR0727') AND B9_DATA BETWEEN '20260601' AND '20260930'
  AND D_E_L_E_T_ = ' '
ORDER BY B9_COD, B9_DATA;

-- 3) Movimentos internos do mes (SD3): producao (D3_CF PR0/PR1), requisicoes e devolucoes, com o custo gravado
SELECT RTRIM(D3_COD) AS PRODUTO, D3_CF AS TIPO, D3_TM AS TM, COUNT(*) AS LINHAS, SUM(D3_QUANT) AS QUANT,
       SUM(D3_CUSTO1) AS CUSTO, SUM(CASE WHEN D3_CUSTO1 = 0 THEN 1 ELSE 0 END) AS LINHAS_CUSTO_ZERO
FROM SD3010
WHERE D3_FILIAL = @FILIAL AND D3_COD IN ('THC31002IBCBR', 'THC31003CIBR', 'BR0727') AND D3_EMISSAO BETWEEN @DE AND @ATE
  AND D3_ESTORNO <> 'S' AND D_E_L_E_T_ = ' '
GROUP BY D3_COD, D3_CF, D3_TM
ORDER BY D3_COD, D3_CF;

-- 4) Entradas por nota no mes (SD1): compra ou devolucao, com o custo gravado
SELECT RTRIM(D1_COD) AS PRODUTO, D1_TIPO AS TIPO, D1_TES AS TES, COUNT(*) AS LINHAS, SUM(D1_QUANT) AS QUANT,
       SUM(D1_TOTAL) AS TOTAL, SUM(D1_CUSTO) AS CUSTO
FROM SD1010
WHERE D1_FILIAL = @FILIAL AND D1_COD IN ('THC31002IBCBR', 'THC31003CIBR', 'BR0727') AND D1_DTDIGIT BETWEEN @DE AND @ATE
  AND D_E_L_E_T_ = ' '
GROUP BY D1_COD, D1_TIPO, D1_TES
ORDER BY D1_COD;

-- 5) Todas as saidas do mes desses produtos (SD2): quantas com e sem custo, por armazem
SELECT RTRIM(D2_COD) AS PRODUTO, D2_LOCAL AS ARMAZEM, D2_TES AS TES, COUNT(*) AS LINHAS,
       SUM(CASE WHEN D2_CUSTO1 > 0 THEN 1 ELSE 0 END) AS COM_CUSTO, SUM(D2_QUANT) AS QUANT, SUM(D2_CUSTO1) AS CUSTO
FROM SD2010
WHERE D2_FILIAL = @FILIAL AND D2_COD IN ('THC31002IBCBR', 'THC31003CIBR', 'BR0727') AND D2_EMISSAO BETWEEN @DE AND @ATE
  AND D_E_L_E_T_ = ' '
GROUP BY D2_COD, D2_LOCAL, D2_TES
ORDER BY D2_COD;
