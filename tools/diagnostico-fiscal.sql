-- TDash: diagnostico do Fiscal (novos paineis: ICMS, IPI, PIS/COFINS, ISS retido, DIFAL e simulador da reforma)
--
-- SOMENTE LEITURA: so SELECT, nada e criado nem alterado. Sem dado de pessoa (participante so pelo codigo).
-- Objetivo: confirmar quais campos dos livros fiscais (SF3/SFT) e da apuracao estao preenchidos no ambiente,
-- antes de desenhar os paineis.
--
-- Antes de rodar:
--   1. troque o sufixo 010 (empresa 01) pelo da empresa usada no TDash;
--   2. ajuste a filial (1001, 1002...) e o periodo abaixo (um trimestre recente basta).
-- Escrito para SQL Server. Mande o resultado de cada consulta numerada.
-- A PARTE A so le o dicionario e sempre roda. Na PARTE B, se alguma consulta der "Invalid column name",
-- pule essa e siga para a proxima (a parte A ja mostra que o campo nao existe).

DECLARE @FILIAL VARCHAR(10) = '1001';   -- 4 digitos, a mesma filial do app
DECLARE @DE     VARCHAR(8)  = '20260701';
DECLARE @ATE    VARCHAR(8)  = '20260930';

-- ===================== PARTE A: dicionario =====================

-- A1) Campos fiscais do livro por item (SFT) e por nota (SF3) que interessam aos paineis
SELECT RTRIM(X3_ARQUIVO) AS TABELA, RTRIM(X3_CAMPO) AS CAMPO, RTRIM(X3_TITULO) AS TITULO, RTRIM(X3_DESCRIC) AS DESCRICAO,
       X3_TIPO AS TIPO, X3_TAMANHO AS TAMANHO
FROM SX3010
WHERE D_E_L_E_T_ = ' ' AND X3_ARQUIVO IN ('SFT', 'SF3')
  AND (X3_CAMPO LIKE '%CST%' OR X3_CAMPO LIKE '%CLASFIS%' OR X3_CAMPO LIKE '%POSIPI%' OR X3_CAMPO LIKE '%ISS%'
       OR X3_CAMPO LIKE '%DIFAL%' OR X3_CAMPO LIKE '%FCP%' OR X3_CAMPO LIKE '%ICMSCOM%' OR X3_CAMPO LIKE '%PDDES%'
       OR X3_CAMPO LIKE '%PDORI%' OR X3_CAMPO LIKE '%BASEDES%' OR X3_CAMPO LIKE '%PIS%' OR X3_CAMPO LIKE '%COF%'
       OR X3_CAMPO LIKE '%IPI%' OR X3_CAMPO LIKE '%ALIQ%' OR X3_CAMPO LIKE '%BASE%' OR X3_CAMPO LIKE '%IDTRIB%'
       OR X3_CAMPO LIKE '%CBS%' OR X3_CAMPO LIKE '%IBS%' OR X3_CAMPO LIKE '%CLASTR%' OR X3_CAMPO LIKE '%CCLASS%')
ORDER BY X3_ARQUIVO, X3_ORDEM;

-- A2) Tabelas de apuracao e lancamentos fiscais existentes no dicionario
SELECT RTRIM(X2_CHAVE) AS TABELA, RTRIM(X2_NOME) AS NOME
FROM SX2010
WHERE D_E_L_E_T_ = ' ' AND X2_CHAVE IN ('CDH', 'CDA', 'CD2', 'CDC', 'CDV', 'CE0', 'CF8', 'CKR', 'CL2', 'F0I', 'F2D', 'F2B', 'SE2')
ORDER BY X2_CHAVE;

-- A3) Campos da F2D (confere os campos de data, base e aliquota usados em B9)
SELECT RTRIM(X3_CAMPO) AS CAMPO, RTRIM(X3_TITULO) AS TITULO, RTRIM(X3_DESCRIC) AS DESCRICAO, X3_TIPO AS TIPO
FROM SX3010
WHERE D_E_L_E_T_ = ' ' AND X3_ARQUIVO = 'F2D'
ORDER BY X3_ORDEM;

-- ===================== PARTE B: dados do periodo =====================

-- B1) Volume do livro por item no periodo, entradas e saidas
SELECT FT_TIPOMOV AS MOVIMENTO, COUNT(*) AS LINHAS, SUM(FT_VALCONT) AS VALOR_CONTABIL,
       SUM(FT_VALICM) AS ICMS, SUM(FT_VALIPI) AS IPI, SUM(FT_VALPIS) AS PIS, SUM(FT_VALCOF) AS COFINS,
       SUM(FT_ICMSRET) AS ICMS_ST
FROM SFT010
WHERE FT_FILIAL = @FILIAL AND FT_ENTRADA BETWEEN @DE AND @ATE AND FT_DTCANC = ' ' AND D_E_L_E_T_ = ' '
GROUP BY FT_TIPOMOV;

-- B2) ICMS por situacao tributaria (FT_CLASFIS = origem + CST) e sentido
SELECT FT_TIPOMOV AS MOVIMENTO, FT_CLASFIS AS CST_ICMS, COUNT(*) AS LINHAS,
       SUM(FT_BASEICM) AS BASE_ICMS, SUM(FT_VALICM) AS ICMS
FROM SFT010
WHERE FT_FILIAL = @FILIAL AND FT_ENTRADA BETWEEN @DE AND @ATE AND FT_DTCANC = ' ' AND D_E_L_E_T_ = ' '
GROUP BY FT_TIPOMOV, FT_CLASFIS
ORDER BY FT_TIPOMOV, ICMS DESC;

-- B3) PIS/COFINS por CST e sentido (credito aproveitado nas entradas, debito nas saidas)
SELECT FT_TIPOMOV AS MOVIMENTO, FT_CSTPIS AS CST_PIS, FT_CSTCOF AS CST_COFINS, COUNT(*) AS LINHAS,
       SUM(FT_BASEPIS) AS BASE_PIS, SUM(FT_VALPIS) AS PIS, SUM(FT_VALCOF) AS COFINS
FROM SFT010
WHERE FT_FILIAL = @FILIAL AND FT_ENTRADA BETWEEN @DE AND @ATE AND FT_DTCANC = ' ' AND D_E_L_E_T_ = ' '
GROUP BY FT_TIPOMOV, FT_CSTPIS, FT_CSTCOF
ORDER BY FT_TIPOMOV, PIS DESC;

-- B4) Classificacao fiscal (NCM) preenchida? As 20 maiores por valor contabil nas saidas
SELECT TOP 20 FT_POSIPI AS NCM, COUNT(*) AS LINHAS, SUM(FT_VALCONT) AS VALOR_CONTABIL,
       SUM(FT_VALICM) AS ICMS, SUM(FT_VALIPI) AS IPI
FROM SFT010
WHERE FT_FILIAL = @FILIAL AND FT_TIPOMOV = 'S' AND FT_ENTRADA BETWEEN @DE AND @ATE AND FT_DTCANC = ' ' AND D_E_L_E_T_ = ' '
GROUP BY FT_POSIPI
ORDER BY VALOR_CONTABIL DESC;

-- B5) Servicos (F3_TIPO = 'S'): ISS por sentido e retencao (F3_RECISS) e por aliquota
SELECT CASE WHEN F3_CFO < '5' THEN 'ENTRADA (tomado)' ELSE 'SAIDA (prestado)' END AS SENTIDO,
       F3_RECISS AS RETIDO, F3_ALIQICM AS ALIQUOTA, COUNT(*) AS LINHAS, SUM(F3_VALCONT) AS VALOR, SUM(F3_VALICM) AS ISS
FROM SF3010
WHERE F3_FILIAL = @FILIAL AND F3_TIPO = 'S' AND F3_ENTRADA BETWEEN @DE AND @ATE AND F3_DTCANC = ' ' AND D_E_L_E_T_ = ' '
GROUP BY CASE WHEN F3_CFO < '5' THEN 'ENTRADA (tomado)' ELSE 'SAIDA (prestado)' END, F3_RECISS, F3_ALIQICM
ORDER BY SENTIDO, ISS DESC;

-- B6) ISS retido nas notas de entrada (SD1) e nos titulos a pagar (SE2) do periodo
SELECT 'SD1' AS ORIGEM, COUNT(*) AS LINHAS, SUM(D1_VALISS) AS ISS, SUM(D1_TOTAL) AS VALOR
FROM SD1010
WHERE D1_FILIAL = @FILIAL AND D1_DTDIGIT BETWEEN @DE AND @ATE AND D1_VALISS > 0 AND D_E_L_E_T_ = ' '
UNION ALL
SELECT 'SE2', COUNT(*), SUM(E2_ISS), SUM(E2_VALOR)
FROM SE2010
WHERE E2_FILIAL = @FILIAL AND E2_EMISSAO BETWEEN @DE AND @ATE AND E2_ISS > 0 AND D_E_L_E_T_ = ' ';

-- B7) DIFAL e FCP no livro por nota, por UF e sentido
SELECT CASE WHEN F3_CFO < '5' THEN 'ENTRADA' ELSE 'SAIDA' END AS SENTIDO, F3_ESTADO AS UF,
       COUNT(*) AS LINHAS, SUM(F3_DIFAL) AS DIFAL, SUM(F3_ICMSCOM) AS ICMS_COMPLEMENTAR, SUM(F3_VALCONT) AS VALOR
FROM SF3010
WHERE F3_FILIAL = @FILIAL AND F3_ENTRADA BETWEEN @DE AND @ATE AND F3_DTCANC = ' ' AND D_E_L_E_T_ = ' '
  AND (F3_DIFAL > 0 OR F3_ICMSCOM > 0)
GROUP BY CASE WHEN F3_CFO < '5' THEN 'ENTRADA' ELSE 'SAIDA' END, F3_ESTADO
ORDER BY DIFAL DESC;

-- B8) Apuracao de ICMS gravada (CDH): periodos e quantidade de linhas
SELECT TOP 24 CDH_PERIOD AS PERIODO, COUNT(*) AS LINHAS
FROM CDH010
WHERE CDH_FILIAL = @FILIAL AND D_E_L_E_T_ = ' '
GROUP BY CDH_PERIOD
ORDER BY CDH_PERIOD DESC;

-- B9) CBS/IBS (F2D) por mes nas saidas (SD2, pela emissao) e entradas (SD1, pela digitacao) de 2026:
--     aliquota minima e maxima e valor por tributo. Mostra se as entradas tambem tem CBS/IBS (credito no simulador).
SELECT 'SD2' AS ORIGEM, RTRIM(F2B.F2B_TRIB) AS TRIBUTO, LEFT(D2.D2_EMISSAO, 6) AS MES, COUNT(*) AS LINHAS,
       MIN(F2D.F2D_ALIQ) AS ALIQ_MIN, MAX(F2D.F2D_ALIQ) AS ALIQ_MAX, SUM(F2D.F2D_VALOR) AS VALOR
FROM F2D010 F2D
INNER JOIN F2B010 F2B ON F2B.F2B_FILIAL IN (@FILIAL, ' ') AND F2B.F2B_ID = F2D.F2D_IDCAD AND F2B.D_E_L_E_T_ = ' '
INNER JOIN SD2010 D2 ON D2.D2_FILIAL = @FILIAL AND D2.D2_IDTRIB = F2D.F2D_IDREL AND D2.D2_EMISSAO >= '20260101' AND D2.D_E_L_E_T_ = ' '
WHERE F2D.F2D_FILIAL = @FILIAL AND F2D.F2D_TABELA = 'SD2' AND F2D.F2D_DTEXCL = ' ' AND F2D.D_E_L_E_T_ = ' '
  AND (F2B.F2B_TRIB LIKE 'CBS%' OR F2B.F2B_TRIB LIKE 'IBS%')
GROUP BY F2B.F2B_TRIB, LEFT(D2.D2_EMISSAO, 6)
UNION ALL
SELECT 'SD1', RTRIM(F2B.F2B_TRIB), LEFT(D1.D1_DTDIGIT, 6), COUNT(*),
       MIN(F2D.F2D_ALIQ), MAX(F2D.F2D_ALIQ), SUM(F2D.F2D_VALOR)
FROM F2D010 F2D
INNER JOIN F2B010 F2B ON F2B.F2B_FILIAL IN (@FILIAL, ' ') AND F2B.F2B_ID = F2D.F2D_IDCAD AND F2B.D_E_L_E_T_ = ' '
INNER JOIN SD1010 D1 ON D1.D1_FILIAL = @FILIAL AND D1.D1_IDTRIB = F2D.F2D_IDREL AND D1.D1_DTDIGIT >= '20260101' AND D1.D_E_L_E_T_ = ' '
WHERE F2D.F2D_FILIAL = @FILIAL AND F2D.F2D_TABELA = 'SD1' AND F2D.F2D_DTEXCL = ' ' AND F2D.D_E_L_E_T_ = ' '
  AND (F2B.F2B_TRIB LIKE 'CBS%' OR F2B.F2B_TRIB LIKE 'IBS%')
GROUP BY F2B.F2B_TRIB, LEFT(D1.D1_DTDIGIT, 6)
ORDER BY MES DESC, ORIGEM, TRIBUTO;

-- B10) Base de calculo da CBS/IBS nas saidas do periodo, comparada ao valor da mercadoria (D2_TOTAL).
--      Se der "Invalid column name 'F2D_BASE'", pule: a consulta A3 mostra o nome certo do campo de base.
SELECT RTRIM(F2B.F2B_TRIB) AS TRIBUTO, COUNT(*) AS LINHAS, SUM(F2D.F2D_BASE) AS BASE, SUM(D2.D2_TOTAL) AS VALOR_MERCADORIA,
       SUM(F2D.F2D_VALOR) AS VALOR
FROM F2D010 F2D
INNER JOIN F2B010 F2B ON F2B.F2B_FILIAL IN (@FILIAL, ' ') AND F2B.F2B_ID = F2D.F2D_IDCAD AND F2B.D_E_L_E_T_ = ' '
INNER JOIN SD2010 D2 ON D2.D2_FILIAL = @FILIAL AND D2.D2_IDTRIB = F2D.F2D_IDREL AND D2.D2_EMISSAO BETWEEN @DE AND @ATE AND D2.D_E_L_E_T_ = ' '
WHERE F2D.F2D_FILIAL = @FILIAL AND F2D.F2D_TABELA = 'SD2' AND F2D.F2D_DTEXCL = ' ' AND F2D.D_E_L_E_T_ = ' '
  AND (F2B.F2B_TRIB LIKE 'CBS%' OR F2B.F2B_TRIB LIKE 'IBS%')
GROUP BY F2B.F2B_TRIB;
