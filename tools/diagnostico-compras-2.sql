-- TDash: diagnostico de Compras (parte 2) - moeda, diferencas de quantidade e notas sem pedido
--
-- SOMENTE LEITURA: so SELECT, nada e criado nem alterado. Sem dado de pessoa (so numeros de SC, pedido e produto).
-- Continua o diagnostico-compras.sql. Pontos que a primeira rodada deixou em aberto:
--   * o valor entregue (D1_TOTAL) ficou ate 49% acima do valor pedido (C7_QUANT x C7_PRECO) em alguns meses:
--     suspeita de pedido em moeda estrangeira (C7_PRECO na moeda do pedido, D1_TOTAL em reais);
--   * em 391 itens de SC, C1_QUJE e diferente da soma dos pedidos;
--   * 7 itens de nota apontam para um pedido que nao existe na mesma filial;
--   * 43 itens de nota estao em unidade diferente da do pedido.
--
-- Antes de rodar:
--   * Troque o sufixo 010 (empresa 01) pelo da empresa que o TDash vai usar.
--   * @FILIAL: NULL = todas as filiais, ou o codigo como gravado (qualquer tamanho).
--   * Periodo: ultimos 12 meses. Escrito para SQL Server. Mande o resultado de cada consulta numerada.

DECLARE @FILIAL VARCHAR(20) = NULL;
DECLARE @DESDE  CHAR(8) = CONVERT(CHAR(8), DATEADD(MONTH, -12, GETDATE()), 112);

-- 1) Campos de moeda, desconto e imposto do pedido e da nota (existem? tipo e tamanho)
SELECT RTRIM(X3_ARQUIVO) AS TABELA, RTRIM(X3_CAMPO) AS CAMPO, RTRIM(X3_TITULO) AS TITULO, X3_TIPO AS TIPO,
       X3_TAMANHO AS TAMANHO, X3_DECIMAL AS DECIMAIS, X3_CONTEXT AS CONTEXTO
FROM SX3010
WHERE D_E_L_E_T_ = ' '
  AND RTRIM(X3_CAMPO) IN ('C7_MOEDA', 'C7_TXMOEDA', 'C7_TOTAL', 'C7_VLDESC', 'C7_VALIPI', 'C7_FILENT', 'C7_TIPO',
                          'D1_VALDESC', 'D1_VALIPI', 'D1_ICMSRET', 'D1_CUSTO')
ORDER BY X3_ARQUIVO, X3_ORDEM;

-- 2) Itens de pedido que vieram de SC, por moeda do pedido
SELECT C7.C7_MOEDA AS MOEDA, COUNT(*) AS ITENS,
       SUM(C7.C7_QUANT * C7.C7_PRECO) AS VALOR_NA_MOEDA_DO_PEDIDO, SUM(C7.C7_TOTAL) AS SOMA_C7_TOTAL,
       MIN(C7.C7_TXMOEDA) AS TX_MIN, MAX(C7.C7_TXMOEDA) AS TX_MAX
FROM SC7010 C7
WHERE C7.D_E_L_E_T_ = ' ' AND C7.C7_NUMSC <> ' ' AND C7.C7_EMISSAO >= @DESDE
  AND (@FILIAL IS NULL OR C7.C7_FILIAL = @FILIAL)
GROUP BY C7.C7_MOEDA
ORDER BY C7.C7_MOEDA;

-- 3) Por mes e moeda (pedidos com SC): pedido na moeda, pedido convertido pela taxa do pedido e entregue (D1_TOTAL)
SELECT SUBSTRING(C7.C7_EMISSAO, 1, 6) AS MES, C7.C7_MOEDA AS MOEDA,
       SUM(C7.C7_QUANT * C7.C7_PRECO) AS PEDIDO_NA_MOEDA,
       SUM(C7.C7_QUANT * C7.C7_PRECO * CASE WHEN C7.C7_MOEDA > 1 AND C7.C7_TXMOEDA > 0 THEN C7.C7_TXMOEDA ELSE 1 END) AS PEDIDO_CONVERTIDO_PELA_TAXA,
       SUM(ISNULL(N.VALOR, 0)) AS ENTREGUE_D1_TOTAL
FROM SC7010 C7
LEFT JOIN (
  SELECT D1_FILIAL, D1_PEDIDO, D1_ITEMPC, D1_COD, D1_FORNECE, D1_LOJA, SUM(D1_TOTAL) AS VALOR
  FROM SD1010
  WHERE D_E_L_E_T_ = ' ' AND D1_PEDIDO <> ' ' AND D1_TIPO = 'N'
  GROUP BY D1_FILIAL, D1_PEDIDO, D1_ITEMPC, D1_COD, D1_FORNECE, D1_LOJA
) N ON N.D1_FILIAL = C7.C7_FILIAL AND N.D1_PEDIDO = C7.C7_NUM AND N.D1_ITEMPC = C7.C7_ITEM AND N.D1_COD = C7.C7_PRODUTO
   AND N.D1_FORNECE = C7.C7_FORNECE AND N.D1_LOJA = C7.C7_LOJA
WHERE C7.D_E_L_E_T_ = ' ' AND C7.C7_NUMSC <> ' ' AND C7.C7_EMISSAO >= @DESDE
  AND (@FILIAL IS NULL OR C7.C7_FILIAL = @FILIAL)
GROUP BY SUBSTRING(C7.C7_EMISSAO, 1, 6), C7.C7_MOEDA
ORDER BY MES, MOEDA;

-- 4) Os 20 itens com maior excesso de valor da nota sobre o pedido (preco, quantidade, unidade e moeda dos dois lados)
SELECT TOP 20 C7.C7_NUM AS PEDIDO, C7.C7_ITEM AS ITEM, C7.C7_PRODUTO AS PRODUTO, C7.C7_MOEDA AS MOEDA,
       C7.C7_UM AS UM_PEDIDO, N.UM_NF, C7.C7_QUANT AS QTD_PEDIDO, N.QTD AS QTD_NF,
       C7.C7_PRECO AS PRECO_PEDIDO, N.VUNIT AS PRECO_NF,
       C7.C7_QUANT * C7.C7_PRECO AS VALOR_PEDIDO, N.VALOR AS VALOR_NF
FROM SC7010 C7
INNER JOIN (
  SELECT D1_FILIAL, D1_PEDIDO, D1_ITEMPC, D1_COD, D1_FORNECE, D1_LOJA,
         MAX(D1_UM) AS UM_NF, SUM(D1_QUANT) AS QTD, MAX(D1_VUNIT) AS VUNIT, SUM(D1_TOTAL) AS VALOR
  FROM SD1010
  WHERE D_E_L_E_T_ = ' ' AND D1_PEDIDO <> ' ' AND D1_TIPO = 'N'
  GROUP BY D1_FILIAL, D1_PEDIDO, D1_ITEMPC, D1_COD, D1_FORNECE, D1_LOJA
) N ON N.D1_FILIAL = C7.C7_FILIAL AND N.D1_PEDIDO = C7.C7_NUM AND N.D1_ITEMPC = C7.C7_ITEM AND N.D1_COD = C7.C7_PRODUTO
   AND N.D1_FORNECE = C7.C7_FORNECE AND N.D1_LOJA = C7.C7_LOJA
WHERE C7.D_E_L_E_T_ = ' ' AND C7.C7_NUMSC <> ' ' AND C7.C7_EMISSAO >= @DESDE
  AND (@FILIAL IS NULL OR C7.C7_FILIAL = @FILIAL)
  AND N.VALOR > C7.C7_QUANT * C7.C7_PRECO
ORDER BY (N.VALOR - C7.C7_QUANT * C7.C7_PRECO) DESC;

-- 5) Itens de SC em que C1_QUJE difere da soma dos pedidos: C1_QUJE maior, menor ou igual
SELECT SINAL, COUNT(*) AS ITENS_SC
FROM (
  SELECT CASE WHEN C1.C1_QUJE > ISNULL(P.PEDIDO, 0) + 0.001 THEN 'C1_QUJE MAIOR QUE A SOMA DOS PEDIDOS'
              WHEN C1.C1_QUJE < ISNULL(P.PEDIDO, 0) - 0.001 THEN 'C1_QUJE MENOR QUE A SOMA DOS PEDIDOS'
              ELSE 'IGUAL' END AS SINAL
  FROM SC1010 C1
  LEFT JOIN (
    SELECT C7_FILIAL, C7_NUMSC, C7_ITEMSC, C7_PRODUTO, SUM(C7_QUANT) AS PEDIDO
    FROM SC7010 WHERE D_E_L_E_T_ = ' ' AND C7_NUMSC <> ' '
    GROUP BY C7_FILIAL, C7_NUMSC, C7_ITEMSC, C7_PRODUTO
  ) P ON P.C7_FILIAL = C1.C1_FILIAL AND P.C7_NUMSC = C1.C1_NUM AND P.C7_ITEMSC = C1.C1_ITEM AND P.C7_PRODUTO = C1.C1_PRODUTO
  WHERE C1.D_E_L_E_T_ = ' ' AND C1.C1_EMISSAO >= @DESDE AND (@FILIAL IS NULL OR C1.C1_FILIAL = @FILIAL)
) X
GROUP BY SINAL
ORDER BY SINAL;

-- 5b) Amostra: 20 itens de SC com C1_QUJE diferente da soma dos pedidos
SELECT TOP 20 C1.C1_NUM AS SC, C1.C1_ITEM AS ITEM_SC, C1.C1_PRODUTO AS PRODUTO, C1.C1_UM AS UM,
       C1.C1_QUANT AS SOLICITADO, C1.C1_QUJE AS C1_QUJE, P.PEDIDO AS SOMA_PEDIDOS, P.LINHAS AS ITENS_DE_PEDIDO, C1.C1_RESIDUO AS RESIDUO
FROM SC1010 C1
INNER JOIN (
  SELECT C7_FILIAL, C7_NUMSC, C7_ITEMSC, C7_PRODUTO, SUM(C7_QUANT) AS PEDIDO, COUNT(*) AS LINHAS
  FROM SC7010 WHERE D_E_L_E_T_ = ' ' AND C7_NUMSC <> ' '
  GROUP BY C7_FILIAL, C7_NUMSC, C7_ITEMSC, C7_PRODUTO
) P ON P.C7_FILIAL = C1.C1_FILIAL AND P.C7_NUMSC = C1.C1_NUM AND P.C7_ITEMSC = C1.C1_ITEM AND P.C7_PRODUTO = C1.C1_PRODUTO
WHERE C1.D_E_L_E_T_ = ' ' AND C1.C1_EMISSAO >= @DESDE AND (@FILIAL IS NULL OR C1.C1_FILIAL = @FILIAL)
  AND ABS(C1.C1_QUJE - P.PEDIDO) >= 0.001
ORDER BY C1.C1_EMISSAO DESC, C1.C1_NUM, C1.C1_ITEM;

-- 6) Itens de nota que apontam para pedido nao encontrado na mesma filial: ele existe em outra filial, ou deletado?
SELECT D1.D1_FILIAL AS FILIAL_NOTA, D1.D1_PEDIDO AS PEDIDO, D1.D1_ITEMPC AS ITEM_PEDIDO, D1.D1_COD AS PRODUTO, D1.D1_DTDIGIT AS DIGITACAO,
       CASE WHEN EXISTS (SELECT 1 FROM SC7010 X WHERE X.C7_NUM = D1.D1_PEDIDO AND X.C7_ITEM = D1.D1_ITEMPC AND X.D_E_L_E_T_ = ' ')
            THEN 'SIM' ELSE 'NAO' END AS EXISTE_EM_OUTRA_FILIAL,
       CASE WHEN EXISTS (SELECT 1 FROM SC7010 X WHERE X.C7_NUM = D1.D1_PEDIDO AND X.C7_ITEM = D1.D1_ITEMPC
                         AND X.C7_FILENT = D1.D1_FILIAL AND X.D_E_L_E_T_ = ' ')
            THEN 'SIM' ELSE 'NAO' END AS EXISTE_COM_FILIAL_DE_ENTREGA_IGUAL,
       CASE WHEN EXISTS (SELECT 1 FROM SC7010 X WHERE X.C7_NUM = D1.D1_PEDIDO AND X.C7_ITEM = D1.D1_ITEMPC AND X.D_E_L_E_T_ = '*')
            THEN 'SIM' ELSE 'NAO' END AS EXISTE_DELETADO
FROM SD1010 D1
LEFT JOIN SC7010 C7 ON C7.C7_FILIAL = D1.D1_FILIAL AND C7.C7_NUM = D1.D1_PEDIDO AND C7.C7_ITEM = D1.D1_ITEMPC AND C7.D_E_L_E_T_ = ' '
WHERE D1.D_E_L_E_T_ = ' ' AND D1.D1_PEDIDO <> ' ' AND D1.D1_DTDIGIT >= @DESDE AND (@FILIAL IS NULL OR D1.D1_FILIAL = @FILIAL)
  AND C7.C7_NUM IS NULL
ORDER BY D1.D1_DTDIGIT;
