-- TDash: diagnostico de Compras  solicitacao (SC1)  pedido (SC7)  documento de entrada (SD1)
--
-- SOMENTE LEITURA: so SELECT, nada e criado nem alterado.
-- Objetivo: confirmar os campos e o relacionamento SC1  SC7  SD1 antes de criar o acompanhamento
-- "solicitado  pedido  entregue" (em R$, pela emissao da solicitacao).
--   SC1  SC7: C7_FILIAL, C7_NUMSC = C1_NUM, C7_ITEMSC = C1_ITEM, C7_PRODUTO = C1_PRODUTO
--   SC7  SD1: D1_FILIAL, D1_PEDIDO = C7_NUM, D1_ITEMPC = C7_ITEM, D1_COD = C7_PRODUTO,
--              D1_FORNECE = C7_FORNECE, D1_LOJA = C7_LOJA
--
-- Antes de rodar:
--   * Troque o sufixo 010 (empresa 01) pelo da empresa que o TDash vai usar (SC1010, SC7010, SD1010...).
--   * @FILIAL: deixe NULL para todas as filiais, ou informe o codigo como gravado em C1_FILIAL (a consulta 0 lista
--     as filiais). Serve para qualquer tamanho de filial: o SQL Server ignora os espacos a direita ao comparar.
--   * As ligacoes entre SC1, SC7 e SD1 comparam a filial de uma tabela com a da outra. Isso so vale quando as tres tem
--     o mesmo modo de compartilhamento (consulta 1). Se os modos forem diferentes, avise antes de rodar o restante.
--   * Escrito para SQL Server. As consultas 1 a 3 leem o dicionario no banco (SX2/SX3/SIX); se o ambiente
--     ainda usa dicionario em arquivo, pule essas tres.
--   * Periodo: solicitacoes emitidas nos ultimos 12 meses.
--   * Mande o resultado de cada consulta numerada (pode ser print ou CSV).

DECLARE @FILIAL VARCHAR(20) = NULL;   -- NULL = todas as filiais; ou o codigo da filial, de qualquer tamanho
DECLARE @DESDE  CHAR(8) = CONVERT(CHAR(8), DATEADD(MONTH, -12, GETDATE()), 112);

-- 0) Filiais com solicitacao, pedido e nota de entrada nos ultimos 12 meses
SELECT 'SC1' AS TABELA, C1_FILIAL AS FILIAL, COUNT(*) AS ITENS FROM SC1010
WHERE D_E_L_E_T_ = ' ' AND C1_EMISSAO >= @DESDE GROUP BY C1_FILIAL
UNION ALL
SELECT 'SC7', C7_FILIAL, COUNT(*) FROM SC7010
WHERE D_E_L_E_T_ = ' ' AND C7_EMISSAO >= @DESDE GROUP BY C7_FILIAL
UNION ALL
SELECT 'SD1', D1_FILIAL, COUNT(*) FROM SD1010
WHERE D_E_L_E_T_ = ' ' AND D1_DTDIGIT >= @DESDE GROUP BY D1_FILIAL
ORDER BY TABELA, FILIAL;

-- 1) Modo de compartilhamento das tabelas (E = exclusivo, C = compartilhado)
SELECT X2_CHAVE AS TABELA, X2_NOME AS NOME, X2_MODOEMP AS MODO_EMPRESA, X2_MODOUN AS MODO_UNIDADE, X2_MODO AS MODO_FILIAL
FROM SX2010
WHERE D_E_L_E_T_ = ' ' AND X2_CHAVE IN ('SC1', 'SC7', 'SD1')
ORDER BY X2_CHAVE;

-- 2) Campos do relacionamento e de quantidade/valor: existem? tipo, tamanho, contexto (R = real, V = virtual)
SELECT X3_ARQUIVO AS TABELA, X3_CAMPO AS CAMPO, X3_TITULO AS TITULO, X3_TIPO AS TIPO,
       X3_TAMANHO AS TAMANHO, X3_DECIMAL AS DECIMAIS, X3_CONTEXT AS CONTEXTO
FROM SX3010
WHERE D_E_L_E_T_ = ' '
  AND X3_CAMPO IN ('C1_FILIAL', 'C1_NUM', 'C1_ITEM', 'C1_PRODUTO', 'C1_UM', 'C1_QUANT', 'C1_QUJE', 'C1_VUNIT',
                   'C1_TOTAL', 'C1_PEDIDO', 'C1_ITEMPED', 'C1_FORNECE', 'C1_LOJA', 'C1_RESIDUO', 'C1_EMISSAO',
                   'C1_APROV', 'C7_FILIAL', 'C7_NUM', 'C7_ITEM', 'C7_PRODUTO', 'C7_UM', 'C7_QUANT', 'C7_QUJE',
                   'C7_PRECO', 'C7_TOTAL', 'C7_NUMSC', 'C7_ITEMSC', 'C7_FORNECE', 'C7_LOJA', 'C7_RESIDUO',
                   'C7_ENCER', 'C7_EMISSAO', 'C7_CONAPRO', 'D1_FILIAL', 'D1_DOC', 'D1_SERIE', 'D1_ITEM', 'D1_COD',
                   'D1_UM', 'D1_QUANT', 'D1_VUNIT', 'D1_TOTAL', 'D1_PEDIDO', 'D1_ITEMPC', 'D1_FORNECE', 'D1_LOJA',
                   'D1_TIPO', 'D1_DTDIGIT')
ORDER BY X3_ARQUIVO, X3_ORDEM;

-- 3) Indices de SC1, SC7 e SD1 (procure os que comecam por C7_FILIAL+C7_NUMSC e D1_FILIAL+D1_PEDIDO)
SELECT INDICE AS TABELA, ORDEM, CHAVE, DESCRICAO
FROM SIX010
WHERE D_E_L_E_T_ = ' ' AND INDICE IN ('SC1', 'SC7', 'SD1')
ORDER BY INDICE, ORDEM;

-- 4) Itens de solicitacao: quantos tem preco estimado, pedido amarrado, fornecedor sugerido, residuo
SELECT COUNT(*) AS ITENS_SC,
       SUM(CASE WHEN C1_VUNIT > 0 THEN 1 ELSE 0 END) AS COM_PRECO_ESTIMADO,
       SUM(CASE WHEN C1_PEDIDO <> ' ' THEN 1 ELSE 0 END) AS COM_C1_PEDIDO,
       SUM(CASE WHEN C1_QUJE > 0 THEN 1 ELSE 0 END) AS COM_C1_QUJE,
       SUM(CASE WHEN C1_FORNECE <> ' ' THEN 1 ELSE 0 END) AS COM_FORNECEDOR_SUGERIDO,
       SUM(CASE WHEN C1_RESIDUO = 'S' THEN 1 ELSE 0 END) AS RESIDUO_ELIMINADO
FROM SC1010
WHERE D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR C1_FILIAL = @FILIAL) AND C1_EMISSAO >= @DESDE;

-- 5) Itens de pedido: quantos vieram de solicitacao (C7_NUMSC preenchido)
SELECT COUNT(*) AS ITENS_PEDIDO,
       SUM(CASE WHEN C7_NUMSC <> ' ' THEN 1 ELSE 0 END) AS COM_SOLICITACAO,
       SUM(CASE WHEN C7_RESIDUO = 'S' THEN 1 ELSE 0 END) AS RESIDUO_ELIMINADO,
       SUM(CASE WHEN C7_ENCER = 'E' THEN 1 ELSE 0 END) AS ENCERRADOS
FROM SC7010
WHERE D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR C7_FILIAL = @FILIAL) AND C7_EMISSAO >= @DESDE;

-- 6) Pedidos que apontam para uma solicitacao que nao existe na mesma filial, ou com outro produto
SELECT
  SUM(CASE WHEN C1.C1_NUM IS NULL THEN 1 ELSE 0 END) AS SC_NAO_ENCONTRADA_NA_FILIAL,
  SUM(CASE WHEN C1.C1_NUM IS NOT NULL AND C1.C1_PRODUTO <> C7.C7_PRODUTO THEN 1 ELSE 0 END) AS PRODUTO_DIFERENTE,
  SUM(CASE WHEN C1.C1_NUM IS NOT NULL AND C1.C1_UM <> C7.C7_UM THEN 1 ELSE 0 END) AS UNIDADE_DIFERENTE,
  COUNT(*) AS ITENS_PEDIDO_COM_SC
FROM SC7010 C7
LEFT JOIN SC1010 C1 ON C1.C1_FILIAL = C7.C7_FILIAL AND C1.C1_NUM = C7.C7_NUMSC AND C1.C1_ITEM = C7.C7_ITEMSC
                   AND C1.D_E_L_E_T_ = ' '
WHERE C7.D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR C7.C7_FILIAL = @FILIAL) AND C7.C7_NUMSC <> ' ' AND C7.C7_EMISSAO >= @DESDE;

-- 7) Em quantos itens de pedido cada item de solicitacao se divide (1, 2, 3 ou mais)
SELECT QTD_ITENS_PEDIDO, COUNT(*) AS ITENS_SC
FROM (
  SELECT C1.C1_NUM, C1.C1_ITEM, COUNT(C7.C7_NUM) AS QTD_ITENS_PEDIDO
  FROM SC1010 C1
  LEFT JOIN SC7010 C7 ON C7.C7_FILIAL = C1.C1_FILIAL AND C7.C7_NUMSC = C1.C1_NUM AND C7.C7_ITEMSC = C1.C1_ITEM
                     AND C7.C7_PRODUTO = C1.C1_PRODUTO AND C7.D_E_L_E_T_ = ' '
  WHERE C1.D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR C1.C1_FILIAL = @FILIAL) AND C1.C1_EMISSAO >= @DESDE
  GROUP BY C1.C1_NUM, C1.C1_ITEM
) X
GROUP BY QTD_ITENS_PEDIDO
ORDER BY QTD_ITENS_PEDIDO;

-- 8) C1_QUJE bate com a soma de C7_QUANT dos pedidos da SC? (decide se usamos o campo pronto ou a soma)
SELECT
  SUM(CASE WHEN ABS(C1.C1_QUJE - ISNULL(P.PEDIDO, 0)) < 0.001 THEN 1 ELSE 0 END) AS IGUAL,
  SUM(CASE WHEN ABS(C1.C1_QUJE - ISNULL(P.PEDIDO, 0)) >= 0.001 THEN 1 ELSE 0 END) AS DIFERENTE
FROM SC1010 C1
LEFT JOIN (
  SELECT C7_FILIAL, C7_NUMSC, C7_ITEMSC, C7_PRODUTO, SUM(C7_QUANT) AS PEDIDO
  FROM SC7010 WHERE D_E_L_E_T_ = ' ' AND C7_NUMSC <> ' '
  GROUP BY C7_FILIAL, C7_NUMSC, C7_ITEMSC, C7_PRODUTO
) P ON P.C7_FILIAL = C1.C1_FILIAL AND P.C7_NUMSC = C1.C1_NUM AND P.C7_ITEMSC = C1.C1_ITEM AND P.C7_PRODUTO = C1.C1_PRODUTO
WHERE C1.D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR C1.C1_FILIAL = @FILIAL) AND C1.C1_EMISSAO >= @DESDE;

-- 9) Itens de nota por tipo e se tem pedido amarrado (D1_TIPO: N normal, D devolucao, C complemento...)
SELECT D1_TIPO AS TIPO, COUNT(*) AS ITENS,
       SUM(CASE WHEN D1_PEDIDO <> ' ' THEN 1 ELSE 0 END) AS COM_PEDIDO
FROM SD1010
WHERE D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR D1_FILIAL = @FILIAL) AND D1_DTDIGIT >= @DESDE
GROUP BY D1_TIPO
ORDER BY D1_TIPO;

-- 10) Notas que apontam para pedido: pedido nao encontrado, outro produto, outro fornecedor/loja, outra unidade
SELECT
  SUM(CASE WHEN C7.C7_NUM IS NULL THEN 1 ELSE 0 END) AS PEDIDO_NAO_ENCONTRADO_NA_FILIAL,
  SUM(CASE WHEN C7.C7_NUM IS NOT NULL AND C7.C7_PRODUTO <> D1.D1_COD THEN 1 ELSE 0 END) AS PRODUTO_DIFERENTE,
  SUM(CASE WHEN C7.C7_NUM IS NOT NULL AND (C7.C7_FORNECE <> D1.D1_FORNECE OR C7.C7_LOJA <> D1.D1_LOJA) THEN 1 ELSE 0 END) AS FORNECEDOR_DIFERENTE,
  SUM(CASE WHEN C7.C7_NUM IS NOT NULL AND C7.C7_UM <> D1.D1_UM THEN 1 ELSE 0 END) AS UNIDADE_DIFERENTE,
  COUNT(*) AS ITENS_NOTA_COM_PEDIDO
FROM SD1010 D1
LEFT JOIN SC7010 C7 ON C7.C7_FILIAL = D1.D1_FILIAL AND C7.C7_NUM = D1.D1_PEDIDO AND C7.C7_ITEM = D1.D1_ITEMPC
                   AND C7.D_E_L_E_T_ = ' '
WHERE D1.D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR D1.D1_FILIAL = @FILIAL) AND D1.D1_PEDIDO <> ' ' AND D1.D1_DTDIGIT >= @DESDE;

-- 11) C7_QUJE bate com a soma de D1_QUANT das notas normais do pedido?
SELECT
  SUM(CASE WHEN ABS(C7.C7_QUJE - ISNULL(N.ENTREGUE, 0)) < 0.001 THEN 1 ELSE 0 END) AS IGUAL,
  SUM(CASE WHEN ABS(C7.C7_QUJE - ISNULL(N.ENTREGUE, 0)) >= 0.001 THEN 1 ELSE 0 END) AS DIFERENTE
FROM SC7010 C7
LEFT JOIN (
  SELECT D1_FILIAL, D1_PEDIDO, D1_ITEMPC, D1_COD, D1_FORNECE, D1_LOJA, SUM(D1_QUANT) AS ENTREGUE
  FROM SD1010 WHERE D_E_L_E_T_ = ' ' AND D1_PEDIDO <> ' ' AND D1_TIPO = 'N'
  GROUP BY D1_FILIAL, D1_PEDIDO, D1_ITEMPC, D1_COD, D1_FORNECE, D1_LOJA
) N ON N.D1_FILIAL = C7.C7_FILIAL AND N.D1_PEDIDO = C7.C7_NUM AND N.D1_ITEMPC = C7.C7_ITEM AND N.D1_COD = C7.C7_PRODUTO
   AND N.D1_FORNECE = C7.C7_FORNECE AND N.D1_LOJA = C7.C7_LOJA
WHERE C7.D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR C7.C7_FILIAL = @FILIAL) AND C7.C7_EMISSAO >= @DESDE;

-- 12) Totais em R$ por mes de emissao da SC: solicitado (preco estimado), pedido e entregue
SELECT SUBSTRING(C1.C1_EMISSAO, 1, 6) AS MES,
       SUM(C1.C1_QUANT * C1.C1_VUNIT) AS SOLICITADO_PRECO_ESTIMADO,
       SUM(ISNULL(P.VALOR_PEDIDO, 0)) AS PEDIDO,
       SUM(ISNULL(P.VALOR_ENTREGUE, 0)) AS ENTREGUE,
       SUM(CASE WHEN C1.C1_VUNIT = 0 THEN 1 ELSE 0 END) AS ITENS_SEM_PRECO_ESTIMADO,
       COUNT(*) AS ITENS_SC
FROM SC1010 C1
LEFT JOIN (
  SELECT C7.C7_FILIAL, C7.C7_NUMSC, C7.C7_ITEMSC, C7.C7_PRODUTO,
         SUM(C7.C7_QUANT * C7.C7_PRECO) AS VALOR_PEDIDO, SUM(ISNULL(N.VALOR, 0)) AS VALOR_ENTREGUE
  FROM SC7010 C7
  LEFT JOIN (
    SELECT D1_FILIAL, D1_PEDIDO, D1_ITEMPC, D1_COD, D1_FORNECE, D1_LOJA, SUM(D1_TOTAL) AS VALOR
    FROM SD1010 WHERE D_E_L_E_T_ = ' ' AND D1_PEDIDO <> ' ' AND D1_TIPO = 'N'
    GROUP BY D1_FILIAL, D1_PEDIDO, D1_ITEMPC, D1_COD, D1_FORNECE, D1_LOJA
  ) N ON N.D1_FILIAL = C7.C7_FILIAL AND N.D1_PEDIDO = C7.C7_NUM AND N.D1_ITEMPC = C7.C7_ITEM AND N.D1_COD = C7.C7_PRODUTO
     AND N.D1_FORNECE = C7.C7_FORNECE AND N.D1_LOJA = C7.C7_LOJA
  WHERE C7.D_E_L_E_T_ = ' ' AND C7.C7_NUMSC <> ' '
  GROUP BY C7.C7_FILIAL, C7.C7_NUMSC, C7.C7_ITEMSC, C7.C7_PRODUTO
) P ON P.C7_FILIAL = C1.C1_FILIAL AND P.C7_NUMSC = C1.C1_NUM AND P.C7_ITEMSC = C1.C1_ITEM AND P.C7_PRODUTO = C1.C1_PRODUTO
WHERE C1.D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR C1.C1_FILIAL = @FILIAL) AND C1.C1_EMISSAO >= @DESDE
GROUP BY SUBSTRING(C1.C1_EMISSAO, 1, 6)
ORDER BY MES;

-- 13) Amostra: 20 itens de SC com pedido parcial ou entrega parcial (quantidades e valores, sem dado de pessoa)
SELECT TOP 20 C1.C1_NUM AS SC, C1.C1_ITEM AS ITEM_SC, C1.C1_PRODUTO AS PRODUTO, C1.C1_UM AS UM,
       C1.C1_QUANT AS SOLICITADO, C1.C1_QUJE AS C1_QUJE, C1.C1_VUNIT AS PRECO_ESTIMADO,
       ISNULL(P.PEDIDO, 0) AS PEDIDO, ISNULL(P.ENTREGUE, 0) AS ENTREGUE, P.PEDIDOS AS QTD_ITENS_PEDIDO
FROM SC1010 C1
INNER JOIN (
  SELECT C7.C7_FILIAL, C7.C7_NUMSC, C7.C7_ITEMSC, C7.C7_PRODUTO,
         SUM(C7.C7_QUANT) AS PEDIDO, SUM(C7.C7_QUJE) AS ENTREGUE, COUNT(*) AS PEDIDOS
  FROM SC7010 C7
  WHERE C7.D_E_L_E_T_ = ' ' AND C7.C7_NUMSC <> ' '
  GROUP BY C7.C7_FILIAL, C7.C7_NUMSC, C7.C7_ITEMSC, C7.C7_PRODUTO
) P ON P.C7_FILIAL = C1.C1_FILIAL AND P.C7_NUMSC = C1.C1_NUM AND P.C7_ITEMSC = C1.C1_ITEM AND P.C7_PRODUTO = C1.C1_PRODUTO
WHERE C1.D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR C1.C1_FILIAL = @FILIAL) AND C1.C1_EMISSAO >= @DESDE
  AND (P.PEDIDO < C1.C1_QUANT OR P.ENTREGUE < P.PEDIDO)
ORDER BY C1.C1_EMISSAO DESC, C1.C1_NUM, C1.C1_ITEM;

-- 14) Pedido com mais de uma linha para o mesmo numero e item (C7_SEQUEN ou grade C7_ITEMGRD).
--     A nota so aponta pedido + item (D1_PEDIDO + D1_ITEMPC); se houver linhas repetidas, a entrega precisa ser
--     somada por numero + item, e nao por linha do pedido.
SELECT COUNT(*) AS PEDIDO_ITEM_COM_MAIS_DE_UMA_LINHA, ISNULL(MAX(LINHAS), 0) AS MAIOR_QUANTIDADE_DE_LINHAS
FROM (
  SELECT C7_FILIAL, C7_NUM, C7_ITEM, COUNT(*) AS LINHAS
  FROM SC7010
  WHERE D_E_L_E_T_ = ' ' AND (@FILIAL IS NULL OR C7_FILIAL = @FILIAL) AND C7_EMISSAO >= @DESDE
  GROUP BY C7_FILIAL, C7_NUM, C7_ITEM
  HAVING COUNT(*) > 1
) X;
